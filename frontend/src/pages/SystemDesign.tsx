import { useEffect, useRef, useState } from "react";
import { useParams } from "react-router-dom";
import { FileDown, Loader2, LayoutDashboard } from "lucide-react";
import { Button } from "@/components/ui/button";
import { useWorkspaceRepo } from "@/hooks/use-workspace-repo";
import { useCompactMode } from "@/hooks/use-compact-mode";
import { generateSystemDesign } from "@/lib/api";
import type { RepoMeta } from "@/lib/mock-data";
import { useToast } from "@/hooks/use-toast";
import WorkspaceNav from "@/components/layout/WorkspaceNav";
import NoRepoLoaded from "@/components/layout/NoRepoLoaded";
import ReactMarkdown from "react-markdown";
import jsPDF from "jspdf";

const SystemDesign = () => {
  const { repoId } = useParams();
  const { meta, repoContext, repoId: canonicalId } = useWorkspaceRepo(repoId);
  if (!meta) return <div className="min-h-screen bg-background"><WorkspaceNav repoId={repoId ?? ""} active="system-design" /><NoRepoLoaded repoId={repoId} /></div>;
  return <SystemDesignWorkspace key={`${repoId}:${canonicalId}`} routeId={repoId ?? ""} meta={meta} repoContext={repoContext} />;
};

function SystemDesignWorkspace({ routeId, meta, repoContext }: { routeId: string; meta: RepoMeta; repoContext: string }) {
  const { toast } = useToast();
  const compact = useCompactMode();
  const generation = useRef(0);
  const [content, setContent] = useState("");
  const [isGenerating, setIsGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => () => { generation.current += 1; }, []);

  const generate = async () => {
    if (!repoContext || isGenerating) return;
    const attempt = ++generation.current;
    setIsGenerating(true);
    setError(null);
    try {
      const result = await generateSystemDesign(repoContext);
      if (attempt !== generation.current) return;
      if (!result?.trim()) throw new Error("The model returned an empty document. Try generating it again.");
      setContent(result);
    } catch (failure) {
      if (attempt === generation.current) setError(failure instanceof Error ? failure.message : "Could not generate the document.");
    } finally {
      if (attempt === generation.current) setIsGenerating(false);
    }
  };

  const downloadPDF = () => {
    if (!content) return;
    try {
      const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
      const margin = 15;
      const maxWidth = doc.internal.pageSize.getWidth() - margin * 2;
      let y = 20;
      const addText = (text: string, size: number, bold = false, color: [number, number, number] = [30, 30, 30]) => {
        doc.setFontSize(size);
        doc.setFont("helvetica", bold ? "bold" : "normal");
        doc.setTextColor(...color);
        for (const line of doc.splitTextToSize(text, maxWidth)) {
          if (y > 275) { doc.addPage(); y = 20; }
          doc.text(line, margin, y);
          y += size * 0.45;
        }
        y += 2;
      };
      addText(`System Design: ${meta.owner}/${meta.name}`, 18, true, [20, 20, 20]);
      y += 4;
      addText("AI-generated by GitPlus. Verify against the repository source.", 9, false, [120, 120, 120]);
      y += 8;
      for (const line of content.split("\n")) {
        if (line.startsWith("# ")) { y += 6; addText(line.slice(2), 16, true); }
        else if (line.startsWith("## ")) { y += 4; addText(line.slice(3), 13, true, [40, 40, 40]); }
        else if (line.startsWith("### ")) { y += 2; addText(line.slice(4), 11, true, [60, 60, 60]); }
        else if (line.startsWith("```")) continue;
        else if (line.startsWith("- ")) addText(`  • ${line.slice(2)}`, 9);
        else if (line.trim()) addText(line, 9);
        else y += 3;
      }
      doc.save(`system-design-${meta.name}.pdf`);
    } catch (failure) {
      toast({ title: "PDF export failed", description: failure instanceof Error ? failure.message : "Could not create the PDF.", variant: "destructive" });
    }
  };

  return <div className="min-h-screen bg-background">
    <WorkspaceNav repoId={routeId} owner={meta.owner} name={meta.name} active="system-design" actions={<>
      {content && <Button onClick={downloadPDF} aria-label="Download as PDF" className="min-h-11 gap-2 text-sm sm:min-h-9"><FileDown className="h-4 w-4" aria-hidden="true" />PDF</Button>}
      <Button onClick={() => void generate()} disabled={isGenerating || !repoContext} variant="outline" className="min-h-11 gap-2 text-sm sm:min-h-9">{isGenerating ? <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" /> : <LayoutDashboard className="h-4 w-4" aria-hidden="true" />}{isGenerating ? "Generating…" : content ? "Regenerate" : "Generate"}</Button>
    </>} />
    <main id="main-content" tabIndex={-1} className={`mx-auto w-full max-w-4xl px-4 sm:px-6 ${compact ? "py-5" : "py-8"}`}>
      <h1 className="text-2xl font-semibold tracking-tight">System design</h1>
      <p className="mt-2 text-sm leading-relaxed text-muted-foreground">Generate an architecture document from the loaded repository context. AI-generated design descriptions may be incomplete; verify them against the source.</p>
      {!repoContext && <p role="alert" className="mt-5 rounded-lg border border-border p-4 text-sm">Repository context is unavailable. Load source data from the overview first.</p>}
      {error && <div role="alert" className="mt-5 rounded-lg border border-destructive/30 bg-destructive/5 p-4"><h2 className="font-medium">Document generation failed</h2><p className="mt-1 break-words text-sm text-muted-foreground">{error}</p>{content && <p className="mt-1 text-sm text-muted-foreground">The previous document remains available below.</p>}<Button variant="outline" onClick={() => void generate()} className="mt-3 min-h-11 sm:min-h-9">Try again</Button></div>}
      {isGenerating && <div role="status" className="mt-5 flex items-center gap-3 rounded-lg border border-border p-5 text-sm text-muted-foreground"><Loader2 className="h-5 w-5 animate-spin text-primary" aria-hidden="true" />Generating the architecture document…</div>}
      {!content && !isGenerating && !error && repoContext && <div className="mt-5 rounded-lg border border-dashed border-border p-5"><h2 className="font-medium">Document the architecture</h2><p className="mt-1 text-sm leading-relaxed text-muted-foreground">Review the generated design in this workspace, then download it as a PDF.</p><Button onClick={() => void generate()} className="mt-4 min-h-11 sm:min-h-9">Generate document</Button></div>}
      {content && <article aria-label="AI-generated system design" className="mt-6 min-w-0 rounded-lg border border-border bg-card p-4 text-sm leading-relaxed text-secondary-foreground sm:p-6 [&_h1]:mb-4 [&_h1]:text-xl [&_h1]:font-semibold [&_h1]:text-foreground [&_h2]:mb-2 [&_h2]:mt-6 [&_h2]:text-lg [&_h2]:font-semibold [&_h2]:text-foreground [&_h3]:mb-2 [&_h3]:mt-4 [&_h3]:text-base [&_h3]:font-medium [&_h3]:text-foreground [&_p]:mb-3 [&_p]:break-words [&_ul]:mb-3 [&_ul]:list-disc [&_ul]:pl-5 [&_ol]:mb-3 [&_ol]:list-decimal [&_ol]:pl-5 [&_li]:mb-1 [&_a]:text-primary [&_a]:underline [&_code]:break-words [&_code]:rounded [&_code]:bg-muted [&_code]:px-1 [&_code]:font-mono [&_code]:text-sm [&_pre]:my-3 [&_pre]:overflow-x-auto [&_pre]:rounded-md [&_pre]:border [&_pre]:border-border [&_pre]:bg-muted [&_pre]:p-3 [&_pre_code]:break-normal [&_pre_code]:bg-transparent [&_pre_code]:p-0 [&_strong]:text-foreground"><ReactMarkdown>{content}</ReactMarkdown></article>}
    </main>
  </div>;
}

export default SystemDesign;
